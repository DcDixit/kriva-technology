#!/usr/bin/env node
/* Consent regression test for the shared chrome generator. Read-only for the repo.
   1. Every page carries the consent-gated analytics block exactly as apply_chrome.cjs JS_TAG writes it.
   2. Regenerating the chrome (apply_chrome.cjs main) on COPIES in a temp folder keeps consent gating on all pages.
   3. The six build scripts that re-apply the chrome get it from apply_chrome.cjs.
   Usage: node _qa_consent_chrome.cjs   (exit 1 on any failure) */
const fs = require("fs");
const os = require("os");
const path = require("path");

const ROOT = __dirname;
const { JS_TAG, PAGE_CURRENT } = require("./apply_chrome.cjs");
const DEPENDENTS = ["build_markets.cjs", "build_priority3.cjs", "build_priority4.cjs", "build_priority5.cjs", "build_priority6.cjs", "build_supporting.cjs"];

const lf = (s) => s.replace(/\r/g, "");
const between = (s, a, b) => {
  const i = s.indexOf(a);
  const j = s.indexOf(b, i);
  return i < 0 || j < 0 ? null : s.slice(i, j + b.length);
};
const GA_BLOCK = between(JS_TAG, "<!-- KRIVA_GA_START -->", "<!-- KRIVA_CLARITY_END -->");

/* Returns a list of problems for one page's HTML (empty = consent gating intact). */
function checkPage(html) {
  const t = lf(html);
  const problems = [];
  const block = between(t, "<!-- KRIVA_GA_START -->", "<!-- KRIVA_CLARITY_END -->");
  if (!block) problems.push("analytics block missing");
  else if (block !== GA_BLOCK) problems.push("analytics block differs from apply_chrome.cjs JS_TAG");
  if ((t.match(/<!-- KRIVA_GA_START -->/g) || []).length !== 1) problems.push("analytics block not exactly once");
  if (!t.includes('<script src="/shared/chrome.js" defer></script>')) problems.push("chrome.js missing");
  if (!t.includes('<script src="/shared/consent.js" defer></script>')) problems.push("consent.js missing");
  if (!t.includes('<link rel="stylesheet" href="/shared/consent.css">')) problems.push("consent.css missing");
  if (/analytics_storage:\s*\(?navigator\.globalPrivacyControl[^)]*'granted'/.test(t) || /'consent',\s*'default',\{[^}]*analytics_storage:'granted'/.test(t))
    problems.push("analytics granted by default");
  if (/<script[^>]+src="https:\/\/www\.googletagmanager\.com/.test(t)) problems.push("static gtag.js tag (loads before consent)");
  if (/<script[^>]*>\s*\(function\(c,l,a,r,i,t,y\)\{if\(navigator/.test(t) || /src="https:\/\/www\.clarity\.ms/.test(t)) problems.push("static Clarity tag (loads before consent)");
  if (/<link rel="(preconnect|dns-prefetch)" href="https:\/\/www\.(googletagmanager|google-analytics)\.com"/.test(t)) problems.push("preconnect to Google before consent");
  return problems;
}

function report(label, pages, dir) {
  let bad = 0;
  for (const f of pages) {
    const p = path.join(dir, f);
    if (!fs.existsSync(p)) { console.log(`  MISS ${f}`); bad++; continue; }
    const problems = checkPage(fs.readFileSync(p, "utf8"));
    if (problems.length) { bad++; console.log(`  FAIL ${f}: ${problems.join("; ")}`); }
  }
  console.log(`${label}: ${pages.length - bad}/${pages.length} pages pass`);
  return bad === 0;
}

const pages = Object.keys(PAGE_CURRENT).filter((f) => fs.existsSync(path.join(ROOT, f)));
const onDisk = fs.readdirSync(ROOT).filter((f) => /^kriva-.*\.html$|^404\.html$/.test(f));
const notCovered = onDisk.filter((f) => !(f in PAGE_CURRENT));
let ok = true;

// 1. Current pages
ok = report("1. current pages", onDisk, ROOT) && ok;
if (notCovered.length) console.log(`  note: not regenerated by apply_chrome.cjs: ${notCovered.join(", ")}`);

// 2. Regenerate on copies (never touches the repo)
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "kriva-chrome-regen-"));
try {
  fs.mkdirSync(path.join(tmp, "shared"));
  fs.copyFileSync(path.join(ROOT, "apply_chrome.cjs"), path.join(tmp, "apply_chrome.cjs"));
  fs.copyFileSync(path.join(ROOT, "shared", "studio.js"), path.join(tmp, "shared", "studio.js"));
  for (const f of pages) fs.copyFileSync(path.join(ROOT, f), path.join(tmp, f));
  const gen = require(path.join(tmp, "apply_chrome.cjs"));
  const log = console.log;
  console.log = () => {};
  let exit;
  try { exit = gen.main(); } finally { console.log = log; }
  if (exit !== 0) { console.log("  generator reported a FAIL or MISS"); ok = false; }
  ok = report("2. after regenerating chrome on copies", pages, tmp) && ok;
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

// 3. Dependent build scripts take the chrome from apply_chrome.cjs
let depBad = 0;
for (const f of DEPENDENTS) {
  const src = fs.existsSync(path.join(ROOT, f)) ? fs.readFileSync(path.join(ROOT, f), "utf8") : "";
  const imports = /require\(["']\.\/apply_chrome\.cjs["']\)/.test(src) && /applyFile\(/.test(src);
  const ownTag = /KRIVA_GA_START|googletagmanager\.com\/gtag|clarity\.ms\/tag/.test(src);
  if (!imports || ownTag) { depBad++; console.log(`  FAIL ${f}: ${!imports ? "does not use apply_chrome.cjs applyFile" : "writes its own analytics tag"}`); }
}
console.log(`3. build scripts using apply_chrome.cjs: ${DEPENDENTS.length - depBad}/${DEPENDENTS.length}`);
ok = ok && depBad === 0;

console.log(ok ? "PASS consent chrome regression" : "FAIL consent chrome regression");
process.exit(ok ? 0 : 1);
